#!/usr/bin/env python3
"""Embed compiled SPIR-V modules into a C++ header.

The generated header is intentionally self-contained and uses inline
constexpr std::array objects so it can be included from multiple translation
units without creating duplicate symbols.
"""

import argparse
from pathlib import Path

SPIRV_MAGIC = 0x07230203

SHADERS = [
    ("present.vert", "PresentVert"),
    ("present.frag", "PresentFrag"),
    ("easu.comp", "EasuComp"),
    ("rcas.comp", "RcasComp"),
]


def parse_args() -> argparse.Namespace:
    root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--spv-dir",
        type=Path,
        default=root / "shaders",
        help="directory containing the compiled .spv files",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=root / "src" / "generated" / "spirv_data.h",
        help="generated C++ header path",
    )
    return parser.parse_args()


def load_words(path: Path) -> tuple[bytes, list[int]]:
    data = path.read_bytes()
    if not data:
        raise SystemExit(f"empty SPIR-V file: {path}")
    if len(data) % 4 != 0:
        raise SystemExit(f"SPIR-V size is not a multiple of 4 bytes: {path}")
    words = [int.from_bytes(data[offset : offset + 4], "little") for offset in range(0, len(data), 4)]
    if words[0] != SPIRV_MAGIC:
        raise SystemExit(f"invalid SPIR-V magic in {path}: 0x{words[0]:08x}")
    return data, words


def main() -> None:
    args = parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "// Generated by tools/embed_spirv.py. Do not edit.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace psxreborn::embedded_shaders {",
        "",
    ]

    for name, symbol in SHADERS:
        data, words = load_words(args.spv_dir / f"{name}.spv")
        lines.append(f"inline constexpr std::array<uint32_t, {len(words)}> k{symbol}Spirv = {{")
        for offset in range(0, len(words), 8):
            chunk = words[offset : offset + 8]
            lines.append("    " + ", ".join(f"0x{word:08x}u" for word in chunk) + ",")
        lines.append("};")
        lines.append(f"inline constexpr uint32_t k{symbol}SpirvSizeBytes = {len(data)}u;")
        lines.append("")

    lines.append("}  // namespace psxreborn::embedded_shaders")
    lines.append("")
    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
